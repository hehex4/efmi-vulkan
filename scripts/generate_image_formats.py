"""Generate core Vulkan image format facts from the installed pinned registry."""
from __future__ import annotations
import argparse
import hashlib
import re
from pathlib import Path
import xml.etree.ElementTree as ET
from build import find_vulkan_include

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "frontend/gpu/image_formats.h"


def generated() -> str:
    registry = Path(find_vulkan_include()).parent / "registry/vk.xml"
    data = registry.read_bytes()
    root = ET.fromstring(data)
    enums = root.find("enums[@name='VkFormat']")
    names = {int(e.attrib["value"]): e.attrib["name"] for e in enums
             if "value" in e.attrib and 0 < int(e.attrib["value"]) <= 184}
    if set(names) != set(range(1, 185)):
        raise RuntimeError("Core Vulkan format inventory changed")
    formats = {f.attrib["name"]: f for f in root.find("formats")}
    classes = {name: i + 1 for i, name in enumerate(sorted({formats[n].attrib["class"] for n in names.values()}))}
    spirv = Path("F:/vulkan/SPIRV-Reflect-1.4.321.0/include/spirv/unified1/spirv.h").read_bytes()
    storage_formats = {name: int(value) for name, value in re.findall(rb"SpvImageFormat(\w+)\s*=\s*(\d+)", spirv)}
    lines = ["// Generated by scripts/generate_image_formats.py; do not edit.",
             "// Vulkan-Headers registry SHA-256: " + hashlib.sha256(data).hexdigest(),
             "// SPIR-V enum header SHA-256: " + hashlib.sha256(spirv).hexdigest(),
             "#pragma once", "#include <vulkan/vulkan.h>", "namespace efmi::gpu {",
             "struct ImageFormatInfo {", "    VkExtent3D block;",
             "    uint32_t bytes,compatibility,compression; // Compression: 0 none, 1 BC, 2 ETC/EAC, 3 ASTC.",
             "    VkImageAspectFlags aspects;", "    uint32_t depth_bytes;", "    bool color_clear;",
             "    uint32_t scalar_type,storage_format; // Shader scalar: 1 float, 2 unsigned, 3 signed.", "};",
             "inline constexpr ImageFormatInfo image_formats[185]={", "    {}, // VK_FORMAT_UNDEFINED"]
    for i in range(1, 185):
        name = names[i]
        f = formats[name]
        a = f.attrib
        components = {c.attrib["name"]: c.attrib["bits"] for c in f.findall("component")}
        aspects = (2 if "D" in components else 0) | (4 if "S" in components else 0)
        if not aspects:
            aspects = 1
        depth_bytes = (int(components["D"]) + 7) // 8 if "D" in components else 0
        if depth_bytes == 3:
            depth_bytes = 4  # D24 buffer transfers use one 32-bit word per depth value.
        compression = {None: 0, "BC": 1, "ETC2": 2, "EAC": 2, "ASTC LDR": 3}[a.get("compressed")]
        clear = aspects == 1 and compression == 0 and not (components.get("B") == "64")
        numeric = [c.attrib["numericFormat"] for c in f.findall("component")]
        scalar = 1 if aspects & 2 else 2 if aspects == 4 or numeric[0] == "UINT" else 3 if numeric[0] == "SINT" else 1
        spv_format = f.find("spirvimageformat")
        storage = storage_formats[spv_format.attrib["name"].encode()] if spv_format is not None else 0
        lines.append("    {{%s},%s,%d,%d,%d,%d,%s,%d,%d}, // %s" %
                     (a.get("blockExtent", "1,1,1"), a["blockSize"], classes[a["class"]],
                      compression, aspects, depth_bytes, str(clear).lower(), scalar, storage, name))
    lines += ["};", "}", ""]
    return "\n".join(lines)


def verify() -> None:
    if TARGET.read_text(encoding="ascii") != generated():
        raise RuntimeError("Image format facts are stale; regenerate from the pinned Vulkan registry")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    if args.write:
        TARGET.write_text(generated(), encoding="ascii", newline="\n")
    else:
        verify()
    print("Core image format facts: 184 formats verified")
